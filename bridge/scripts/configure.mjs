import fs from 'node:fs';
import path from 'node:path';
import { opaque,passwordHash } from '../server/security.mjs';
const [baseUrl,outputDirectory]=process.argv.slice(2);
if(!baseUrl||!outputDirectory)throw new Error('Usage: node bridge/scripts/configure.mjs https://your-domain /private/config-directory');
const url=new URL(baseUrl);
if(url.protocol!=='https:'||url.pathname!=='/'||url.search||url.hash||url.username||url.password)throw new Error('Supply an HTTPS origin');
fs.mkdirSync(outputDirectory,{recursive:true,mode:0o700});
for(const filename of ['server-config.json','owner-password.txt'])if(fs.existsSync(path.join(outputDirectory,filename)))throw new Error('Configuration exists. Reuse it during upgrades; do not replace credentials.');
const password=opaque();
const config={baseUrl:url.origin,port:8787,dataDir:path.resolve(outputDirectory,'data'),ownerUsername:'owner',ownerPasswordHash:await passwordHash(password),devices:[]};
if(process.env.BRIDGE_GOOGLE_CLIENT_ID&&process.env.BRIDGE_GOOGLE_CLIENT_SECRET)config.google={clientId:process.env.BRIDGE_GOOGLE_CLIENT_ID,clientSecret:process.env.BRIDGE_GOOGLE_CLIENT_SECRET};
fs.writeFileSync(path.join(outputDirectory,'server-config.json'),JSON.stringify(config,null,2),{mode:0o600,flag:'wx'});
fs.writeFileSync(path.join(outputDirectory,'owner-password.txt'),password+'\n',{mode:0o600,flag:'wx'});
console.log('Private server configuration created. Devices pair through account approval; no device keys are generated manually.');
