import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {Client} from '@modelcontextprotocol/sdk/client/index.js';
import {StreamableHTTPClientTransport} from '@modelcontextprotocol/sdk/client/streamableHttp.js';
import {startServer} from '../server/index.mjs';
import {opaque,hash,passwordHash} from '../server/security.mjs';

test('MCP distinguishes inline screenshot results from file-only results and serves all widget versions',async t=>{
 const directory=fs.mkdtempSync(path.join(os.tmpdir(),'bridge-screenshot-mcp-'));
 const diagnostics=[];
 const server=await startServer({baseUrl:'http://127.0.0.1:9876',port:0,dataDir:directory,ownerPasswordHash:await passwordHash('test-password'),devices:[{id:'p111',name:'PC',tokenHash:hash(opaque())}]},{toolDiagnostics:event=>diagnostics.push(event)});
 const token=opaque();
 server.store.saveGrant(hash(token),'access','screenshot-test',{clientId:'screenshot-test',ownerId:'owner',scopes:['desktop']},Date.now()+90000);
 const client=new Client({name:'screenshot-test',version:'1'},{capabilities:{}});
 t.after(async()=>{await client.close();await server.close();fs.rmSync(directory,{recursive:true,force:true});});
 await client.connect(new StreamableHTTPClientTransport(new URL('http://127.0.0.1:'+server.httpServer.address().port+'/mcp'),{requestInit:{headers:{authorization:'Bearer '+token}}}));
 server.broker.tools=()=>[{name:'cua_get_desktop_state',inputSchema:{type:'object',properties:{}}}];
 const catalog=await client.listTools();
 const captureTool=catalog.tools.find(t=>t.name==='cua_get_desktop_state');
 assert.equal(captureTool._meta.ui.resourceUri,'ui://desktop-bridge/screenshot-v8.html');
 assert.equal(captureTool.inputSchema.properties.image_delivery.default,'ui');
 for(const version of [1,2,3,4,5,6,7,8]){
  const r=await client.readResource({uri:'ui://desktop-bridge/screenshot-v'+version+'.html'});
  assert.match(r.contents[0].text,/Persist the identity of the picture/);
  assert.deepEqual(r.contents[0]._meta['openai/ui'],{availableDisplayModes:['inline','fullscreen'],preferredDisplayMode:'inline'});
  assert.deepEqual(r.contents[0]._meta.ui.csp.connectDomains,['http://127.0.0.1:9876']);
  assert.ok(!r.contents[0].text.includes('__DESKTOP_BRIDGE_IMAGE_ORIGIN__'));
 }
 const id='11111111-1111-4111-8111-111111111111';
 server.store.beginCall(id,'p111','cua_get_desktop_state','owner');
 server.store.finishCall(id,'completed',{content:[{type:'image',mimeType:'image/png',data:'AAAA'}]});
 let dispatchedArgs;
 server.broker.call=async(name,args)=>{dispatchedArgs=args;return {content:[{type:'image',mimeType:'image/png',data:'AAAA'}],_meta:{desktopBridge:{callId:id}},structuredContent:{screenshot_width:1600,screenshot_height:900}};};
 const picture=await client.callTool({name:'cua_get_desktop_state',arguments:{}});
 assert.equal(picture.structuredContent.desktopBridgeScreenshotAvailable,true);
 assert.equal(picture.structuredContent.desktopBridgeCallId,id);
 assert.equal(picture.structuredContent.desktopBridgeImageDelivery,'ui');
 assert.equal(picture.content.some(c=>c.type==='image'),false);
 assert.equal(typeof picture._meta.desktopBridge.screenshot.token,'string');
 assert.ok(JSON.stringify(picture).length<2000);
 const vision=await client.callTool({name:'cua_get_desktop_state',arguments:{image_delivery:'model'}});
 assert.equal(vision.content[0].data,'AAAA');
 assert.equal(vision.structuredContent.desktopBridgeImageDelivery,'model');
 assert.equal(dispatchedArgs.image_delivery,undefined,'relay delivery option must not reach the Windows driver');
 server.broker.call=async()=>({content:[{type:'text',text:'Screenshot saved'}],_meta:{desktopBridge:{callId:id}},structuredContent:{screenshot_file_path:'C:\\Temp\\screen.png'}});
 const file=await client.callTool({name:'cua_get_desktop_state',arguments:{}});
 assert.equal(file.structuredContent.desktopBridgeScreenshotAvailable,false);
 assert.equal(file.content.some(c=>c.type==='image'),false);
 server.broker.call=async()=>({isError:true,content:[{type:'text',text:'Capture failed'}]});
 const failed=await client.callTool({name:'cua_get_desktop_state',arguments:{}});
 assert.equal(failed.isError,true);
 assert.equal(failed.structuredContent,undefined);
 // Exercise the authenticated recovery handler, not only the result formatter.
 const imageData='A'.repeat(3_538_284);
 const recoveryId='22222222-2222-4222-8222-222222222222';
 server.store.beginCall(recoveryId,'p111','cua_get_desktop_state','owner');
 server.store.finishCall(recoveryId,'completed',{content:[{type:'image',mimeType:'image/png',data:imageData}],structuredContent:{screenshot_width:1600,screenshot_height:900}});
 const recovered=await client.callTool({name:'get_call_result',arguments:{call_id:recoveryId}});
 assert.ok(recovered.content[0].text.length<1000);
 assert.ok(recovered.content[1].data===imageData);
 assert.equal(JSON.parse(recovered.content[0].text).result.content[0].dataOmitted,true);
 assert.ok(server.store.call(recoveryId,'owner').result.content[0].data===imageData);
 assert.equal(diagnostics.at(-1).tool,'get_call_result');
 assert.equal(diagnostics.at(-1).imageDataChars,imageData.length);
 assert.ok(diagnostics.at(-1).textChars<1000);
 const restoredUi=await client.callTool({name:'get_call_result',arguments:{call_id:recoveryId,image_delivery:'ui'}});
 assert.ok(restoredUi.content[0].text.length<1000);
 assert.equal(restoredUi.content.some(c=>c.type==='image'),false);
 const imageDelivery=restoredUi._meta.desktopBridge.screenshot;
 assert.ok(JSON.stringify(restoredUi).length<2000);
 assert.equal(diagnostics.at(-1).imageCount,0);
 assert.ok(diagnostics.at(-1).metaChars<1000);
 const imageUrl=imageDelivery.url.replace('http://127.0.0.1:9876','http://127.0.0.1:'+server.httpServer.address().port);
 assert.equal(new URL(imageUrl).search,'','access token must not be in URL or access logs');
 const imageResponse=await fetch(imageUrl,{headers:{authorization:'Bearer '+imageDelivery.token,origin:'https://test.web-sandbox.oaiusercontent.com'}});
 assert.equal(imageResponse.status,200);
 assert.equal(imageResponse.headers.get('access-control-allow-origin'),'*');
 assert.equal(imageResponse.headers.get('cache-control'),'no-store');
 assert.deepEqual(Buffer.from(await imageResponse.arrayBuffer()),Buffer.from(imageData,'base64'));
 assert.equal((await fetch(imageUrl)).status,404);
 assert.equal((await fetch(imageUrl,{headers:{authorization:'Bearer '+token}})).status,404,'OAuth token cannot be used as an image capability');
 assert.equal((await fetch(imageUrl.replace(recoveryId,id),{headers:{authorization:'Bearer '+imageDelivery.token}})).status,404);
 const preflight=await fetch(imageUrl,{method:'OPTIONS',headers:{origin:'https://test.web-sandbox.oaiusercontent.com','access-control-request-headers':'authorization'}});
 assert.equal(preflight.status,204);
 assert.equal(preflight.headers.get('access-control-allow-headers'),'Authorization');
 server.store.db.prepare('UPDATE grants SET expires=? WHERE hash=?').run(Date.now()-1,hash(imageDelivery.token));
 assert.equal((await fetch(imageUrl,{headers:{authorization:'Bearer '+imageDelivery.token}})).status,404);
 const renewed=await client.callTool({name:'get_call_result',arguments:{call_id:recoveryId,image_delivery:'ui'}});
 const renewedDelivery=renewed._meta.desktopBridge.screenshot;
 server.store.deleteGrant(hash(token));
 assert.equal((await fetch(imageUrl,{headers:{authorization:'Bearer '+renewedDelivery.token}})).status,404,'revoking source OAuth access immediately revokes image access');
 server.store.db.prepare('INSERT INTO accounts VALUES (?,?,?,?,?)').run('other','other','unused',0,Date.now());
 const otherToken=opaque();
 server.store.saveGrant(hash(otherToken),'access','other',{clientId:'other',ownerId:'other',scopes:['desktop']},Date.now()+90000);
 const otherClient=new Client({name:'other',version:'1'},{capabilities:{}});
 t.after(()=>otherClient.close());
 await otherClient.connect(new StreamableHTTPClientTransport(new URL('http://127.0.0.1:'+server.httpServer.address().port+'/mcp'),{requestInit:{headers:{authorization:'Bearer '+otherToken}}}));
 const denied=await otherClient.callTool({name:'get_call_result',arguments:{call_id:recoveryId}});
 assert.equal(denied.isError,true);
 assert.equal(denied.content.some(c=>c.type==='image'),false);
});
